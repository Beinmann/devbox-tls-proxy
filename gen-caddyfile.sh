#!/usr/bin/env bash
# Generate a Caddyfile from environment variables (no Caddy/Docker needed).
#
#   TARGET       (required) container name on devbox-net
#   CF_API_TOKEN (required) only checked here; Caddy reads it from its env
#   PORTS        default "443:80". Entries separated by commas:
#                  N        listen N -> target N
#                  L:T      listen L -> target T
#                  A-B      ranges, each port N -> N
#                  A-B:C-D  equal-length ranges, paired in order
#   DOMAIN       default localhost.rdrkolaq.de
#   ACME_CA      optional ACME directory URL (e.g. Let's Encrypt staging)
#   HOST_HEADER  "original" (default, pass Host through unchanged) or
#                "target" (send Host: <TARGET>:<port> to the upstream)
#
# Usage: gen-caddyfile.sh              print the Caddyfile
#        gen-caddyfile.sh --list-ports print "<listen> <target>" lines
set -euo pipefail

die() { echo "error: $*" >&2; exit 1; }

# expand "A" or "A-B" into a list of ports, one per line
expand() {
  local s=$1 a b
  if [[ $s =~ ^[0-9]+$ ]]; then a=$s b=$s
  elif [[ $s =~ ^([0-9]+)-([0-9]+)$ ]]; then a=${BASH_REMATCH[1]} b=${BASH_REMATCH[2]}
  else die "invalid port or range '$s' in PORTS"; fi
  a=$((10#$a)); b=$((10#$b))
  (( a >= 1 && b <= 65535 )) || die "port out of range (1-65535) in '$s'"
  (( a <= b )) || die "descending range '$s' in PORTS"
  seq "$a" "$b"
}

# prints "L T" pairs
parse_ports() {
  local spec=${PORTS:-443:80} entry l t
  spec=${spec//[[:space:]]/}
  [[ -n $spec ]] || die "PORTS is empty"
  local -a entries ls ts
  IFS=, read -r -a entries <<< "$spec"
  declare -A seen=()
  for entry in "${entries[@]}"; do
    [[ -n $entry ]] || die "empty entry in PORTS '$spec'"
    if [[ $entry == *:* ]]; then
      l=${entry%%:*} t=${entry#*:}
      [[ $t != *:* ]] || die "invalid entry '$entry' in PORTS"
    else l=$entry t=$entry; fi
    local lo to
    lo=$(expand "$l") || exit 1
    to=$(expand "$t") || exit 1
    mapfile -t ls <<< "$lo"
    mapfile -t ts <<< "$to"
    if [[ $entry == *:* ]]; then
      (( ${#ls[@]} == ${#ts[@]} )) || die "range lengths differ in '$entry'"
    fi
    local i
    for i in "${!ls[@]}"; do
      [[ -z ${seen[${ls[$i]}]:-} ]] || die "duplicate listen port ${ls[$i]} in PORTS"
      seen[${ls[$i]}]=1
      echo "${ls[$i]} ${ts[$i]}"
    done
  done
}

[[ -n ${TARGET:-} ]] || die "TARGET is required (name of the container to proxy to)"
[[ $TARGET =~ ^[A-Za-z0-9][A-Za-z0-9_.-]*$ ]] || die "invalid TARGET '$TARGET' (container name expected)"
[[ -n ${CF_API_TOKEN:-} ]] || die "CF_API_TOKEN is required (Cloudflare token with Zone:DNS:Edit on the zone)"
DOMAIN=${DOMAIN:-localhost.rdrkolaq.de}
[[ $DOMAIN =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]] || die "invalid DOMAIN '$DOMAIN'"
HOST_HEADER=${HOST_HEADER:-original}
[[ $HOST_HEADER == original || $HOST_HEADER == target ]] || die "HOST_HEADER must be 'original' or 'target'"
if [[ -n ${ACME_CA:-} ]]; then
  [[ $ACME_CA =~ ^https?://[^[:space:]{}]+$ ]] || die "invalid ACME_CA '$ACME_CA'"
fi

pairs=$(parse_ports) || exit 1

if [[ ${1:-} == --list-ports ]]; then echo "$pairs"; exit 0; fi
[[ $# -eq 0 ]] || die "unknown argument '$1'"

{
  echo "# generated by gen-caddyfile.sh; do not edit"
  echo "{"
  echo "	admin off"
  echo "	# ports 80/443 of the container are not published: no HTTP->HTTPS redirect"
  echo "	auto_https disable_redirects"
  [[ -z ${ACME_CA:-} ]] || echo "	acme_ca $ACME_CA"
  echo "}"
  while read -r l t; do
    echo
    echo "$DOMAIN:$l {"
    echo "	tls {"
    echo "		dns cloudflare {env.CF_API_TOKEN}"
    echo "	}"
    echo "	reverse_proxy $TARGET:$t {"
    echo "		# no buffering: streaming, SSE and websockets pass through at once"
    echo "		flush_interval -1"
    if [[ $HOST_HEADER == target ]]; then
      echo "		header_up Host {upstream_hostport}"
    fi
    echo "	}"
    echo "}"
  done <<< "$pairs"
}
